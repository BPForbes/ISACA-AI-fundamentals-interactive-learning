// The lab's goals: one per term the lab can teach by doing, across the five
// stages of a project. A goal patches the project's lab into a broken state, sets
// a target the simulation judges, and names the terms the debrief quotes (the
// anchor first). The way to meet the target is the concept the anchor names. The
// brief is story framing for the run's fictional brief; definitions come from the
// term bank, never from here. Every goal carries a solution so that tests can
// prove the setup fails and the solution passes, and the lab can hint.

import type { Brief } from './briefs';
import { defaultLab, type LabConfig, type LabResult } from '../engine/lab';
import { KNOWLEDGE_BASE, type Rule } from '../engine/lab/rules';
import type { Capability } from './upgrades';

export type Stage = 'define' | 'data' | 'train' | 'decide' | 'deploy';

export const STAGES: Stage[] = ['define', 'data', 'train', 'decide', 'deploy'];

export type Goal = {
  anchor: string;
  stage: Stage;
  brief: (b: Brief) => string;
  // The broken starting point, patched onto the lab the project carries.
  setup: (lab: LabConfig, seed: number) => LabConfig;
  goal: { text: string; met: (r: LabResult) => boolean };
  solution: (lab: LabConfig) => LabConfig;
  terms: string[];
  readout: (r: LabResult) => string;
  // Capabilities the fix needs; the goal is posed only when the run has them.
  needs?: Capability[];
};

const say = (b: Brief) => b.owner.charAt(0).toUpperCase() + b.owner.slice(1);
const pct = (v: number) => `${Math.round(v * 100)}%`;
const loss = (r: LabResult) => `validation loss ${r.valLoss.toFixed(2)}`;

type D = Partial<LabConfig['data']>;
type M = Partial<LabConfig['model']>;
const withData = (c: LabConfig, patch: D): LabConfig => ({ ...c, data: { ...c.data, ...patch } });
const withModel = (c: LabConfig, patch: M): LabConfig => ({ ...c, model: { ...c.model, ...patch } });
const withFeatures = (c: LabConfig, patch: Partial<LabConfig['features']>): LabConfig => ({ ...c, features: { ...c.features, ...patch } });
const withReview = (c: LabConfig, patch: Partial<LabConfig['review']>): LabConfig => ({ ...c, review: { ...c.review, ...patch } });
const withDeploy = (c: LabConfig, patch: Partial<LabConfig['deploy']>): LabConfig => ({ ...c, deploy: { ...c.deploy, ...patch } });
const withProblem = (c: LabConfig, patch: Partial<LabConfig['problem']>): LabConfig => ({ ...c, problem: { ...c.problem, ...patch } });

/**
 * What a goal's setup starts from: the lab as the learner left it, re-seeded, with
 * the corruption an earlier goal put in the data (bad rows, wrong labels, scale,
 * drift, a bent world) cleared, so that only this goal's problem is in the way.
 */
const sound = (lab: LabConfig, seed: number): LabConfig => ({
  ...lab,
  data: { ...lab.data, seed, duplicates: 0, outliers: 0, labelNoise: 0, drift: 0, recent: false, curvature: defaultLab(seed).data.curvature },
  features: { ...lab.features, scale: 1 },
  model: { ...lab.model, seed },
});

// Validation loss a sound setup reaches on this data; goals sit a little above it.
export const SOUND_LOSS = 0.42;
// The same in the world that bends more (curvature 6), where a sound model lands a little higher.
export const BENT_LOSS = 0.45;
export const COMPUTE_BUDGET = 1000;

const KB: Rule[] = KNOWLEDGE_BASE.map((k) => k.rule);
const CATCH_ALL: Rule = { feature: 'x', op: '>', value: -3, outcome: 1 };
const noIncident = (r: LabResult, kind: string) => !r.deploy.incidents.some((i) => i.kind === kind);

const lossGoal = (text = `Validation loss at or under ${SOUND_LOSS.toFixed(2)}.`, limit = SOUND_LOSS) => ({ text, met: (r: LabResult) => r.valLoss <= limit });
const decideRead = (r: LabResult) =>
  `accuracy ${pct(r.decided.accuracy)}; ${pct(r.decided.explained)} of decisions explainable (${r.decided.bySource.rule} by rule, ${r.decided.bySource.human} by a reviewer, ${r.decided.bySource.model} by the model, ${r.decided.bySource.default} by default)`;
const deployRead = (r: LabResult) =>
  `value ${r.deploy.value} against a target of ${r.deploy.kgiTarget} over six months, cost ${r.deploy.cost}, ${r.deploy.incidents.length} incident${r.deploy.incidents.length === 1 ? '' : 's'}${r.deploy.alertMonth ? `, drift alert in month ${r.deploy.alertMonth}` : ', no drift alert'}`;

